keep=json.load(open('keep.json'))
def out(t):
    o=0
    for a,b in keep:
        if t<=b: return o+max(0,t-a)
        o+=b-a
    return o
res=[]
for si,seg in enumerate(T):
    for txt,idx in seg:
        s=W[si][idx[0]][1]; e=W[si][idx[-1]][2]
        if si==0 and idx[0]==0: s=0.43
        parts=txt.split('|'); d=(e-s)/len(parts)
        for k,p in enumerate(parts):
            res.append(dict(w=p,s=round(out(s+k*d),3),e=round(out(s+(k+1)*d),3),seg=si,num=any(c.isdigit() for c in p)))
